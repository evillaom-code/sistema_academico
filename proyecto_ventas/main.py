def mostrar_historial_ventas():
    """Muestra los productos comprados y sus cantidades."""
    imprimir_titulo("HISTORIAL DE VENTAS")

    historial = ventas.leer()

    if not historial:
        imprimir_info("Todavía no hay ventas registradas.")
        pausa()
        return

    for venta in sorted(historial, key=lambda v: v.id):
        print(f"\n--- Venta #{venta.id} ---")
        producto = productos.obtener(venta.producto_id)

        if producto is not None:
            print(f"Producto compraaaado: {producto.nombre}")
        else:
            print(f"ID delproducto: {venta.producto_id}")

        print(f"Cntidad comprada: {venta.cantidad}")
        print(f"Precio por unidad: ${venta.precio_unitario:.2f}")
        print(f"Total : ${venta.calcular_total():.2f}")

   
    pausa()


