# =====================================================================

def pausa():
    input("\nPresione Enter para continuar...")


def pedir_entero(etiqueta):
    """Devuelve un entero o None si el usuario escribió otra cosa."""
    try:
        return int(input(etiqueta))
    except ValueError:
        return None


def mostrar_resultado(exito, mensaje):
    # Los controladores devuelven la TUPLA (exito, mensaje)
    if exito:
        imprimir_exito(mensaje)
    else:
        imprimir_error(mensaje)


def mostrar_lista(objetos, vacio="No hay registros todavía."):
    """Sirve para clientes, productos y ventas: cada modelo sabe mostrarse."""
    if not objetos:
        imprimir_info(vacio)
        return
    for objeto in objetos:
        print(f"  {objeto}")
    imprimir_info(f"Total: {len(objetos)}")

def mostrar_productos_por_reponer():
    """Muestra los productos que tienen stock bajo"""
    imprimir_titulo("PRODUCTOS POR REPONER")
    lista_productos=productos.leer()
    productos_bajos=[
        producto for producto in lista_productos
        if producto.stock_bajo()
    ]
    if not productos_bajos:
        imprimir_exito("Todos los produccgos tienen suficcientes stocks.")
    else:
        for producto in productos_bajos:
            print(f"{producto}")
        imprimir_info(
            f"Productos que nesecitan reposicion:{len(productos_bajos)}"
        )
    pausa()


def mostrar_detalle(objeto):
    # Recorre el DICCIONARIO del objeto: clave y valor a la vez
    for clave, valor in objeto.a_diccionario().items():
        print(f"  {str(clave).replace('_', ' ').capitalize():<16}: {valor}")


