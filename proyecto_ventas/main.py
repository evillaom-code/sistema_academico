def registrar_devolucion():
    """Registra la devolución de un producto y recupera su stock."""
    imprimir_titulo("DEVOLUCIÓN DE PRODUCTOS")

    lista_productos = productos.leer()

    if not lista_productos:
        imprimir_error("No hay productos registrados.")
        pausa()
        return

    mostrar_lista(lista_productos)

    try:
        id_producto = pedir_entero("Ingrese el ID del producto que se devuelve: ")
        cantidad = pedir_entero("Ingrese la cantidad que se devuelve: ")

        if cantidad <= 0:
            imprimir_error("La cantidad debe ser mayor que cero.")
            pausa()
            return

        producto = next(
            (p for p in lista_productos if p.id == id_producto),
            None
        )

        if producto is None:
            imprimir_error("No se encontró un producto con ese ID.")
            pausa()
            return

        producto.devolver_stock(cantidad)
        productos.guardar()

        imprimir_exito(
            f"Devolución registrada. Stock actual: {producto.stock}"
        )

    except (ValueError, TypeError, AttributeError) as error:
        imprimir_error(f"No se pudo registrar la devolución: {error}")

    pausa()




